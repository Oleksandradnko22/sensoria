// Builds materials-seed.sql: the meditations and guides that live in the code today, as rows for the new
// database tables (see materials-db-model-migration.sql). Idempotent: running the SQL twice changes nothing new.
// Usage: node --experimental-strip-types scripts/build-materials-seed.mjs   (add --check to only verify it is up to date)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "materials-seed.sql");

// Dollar-quoted literals: no escaping needed, but the tag must not appear inside the text.
const q = (value) => {
  if (value === null || value === undefined) return "null";
  const text = String(value);
  let tag = "t";
  while (text.includes(`$${tag}$`)) tag += "x";
  return `$${tag}$${text}$${tag}$`;
};
const arr = (list) => (list && list.length ? `array[${list.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const json = (value) => (value === undefined || value === null ? "null" : `${q(JSON.stringify(value))}::jsonb`);
const num = (value) => {
  const n = Number(String(value ?? "0").replace(/\s/g, "").replace(",", "."));
  return Number.isFinite(n) ? n : 0;
};

export async function buildSeed() {
  const { meditations } = await import(pathToFileURL(join(root, "src/data/meditations.ts")).href);
  const { guides } = await import(pathToFileURL(join(root, "src/data/guides.ts")).href);

  const firstAuthor = "(select id from public.profiles where role = 'author' order by created_at asc limit 1)";
  const parts = [
    "-- STEP 2: the meditations and guides that live in the app code today, copied into the database.",
    "-- GENERATED by `npm run build:materials-seed` from src/data — do not edit by hand.",
    "-- Run ONCE in the Supabase SQL editor AFTER materials-db-model-migration.sql. Safe to run again.",
    "-- The author is taken from meditation_authors / guide_authors, else the first author account.",
    "-- The app does not read these rows yet (that is the next step), so nothing visible changes.",
    "",
  ];

  for (const m of meditations) {
    parts.push(`do $seed$
declare v_author uuid; v_id uuid;
begin
  v_author := coalesce((select author_id from public.meditation_authors where meditation_id = ${q(m.id)}), ${firstAuthor});
  if v_author is null then raise notice 'No author account yet: skipped meditation ${m.id}'; return; end if;
  select id into v_id from public.content where kind = 'meditation' and slug = ${q(m.id)};
  if v_id is null then
    insert into public.content (author_id, kind, title, description, price, status, tags, slug, duration_minutes)
    values (v_author, 'meditation', ${q(m.title)}, ${q(m.description)}, 0, 'published', ${arr(m.tags)}, ${q(m.id)}, ${m.durationMinutes})
    returning id into v_id;
  end if;
  insert into public.content_meditation_meta (content_id, format, has_embedded_music, offline_download_enabled, background_sound_ids, when_to_use)
  values (v_id, ${q(m.format)}, ${m.hasEmbeddedMusic ? "true" : "false"}, ${m.offlineDownloadEnabled ? "true" : "false"}, ${arr(m.backgroundSoundIds)}, ${arr(m.whenToUse)})
  on conflict (content_id) do update set format = excluded.format, has_embedded_music = excluded.has_embedded_music,
    offline_download_enabled = excluded.offline_download_enabled, background_sound_ids = excluded.background_sound_ids, when_to_use = excluded.when_to_use;
  insert into public.content_meditation_body (content_id, audio_url, transcript)
  values (v_id, ${q(m.audioUrl)}, ${json(m.transcript)})
  on conflict (content_id) do update set audio_url = excluded.audio_url, transcript = excluded.transcript;
end
$seed$;
`);
  }

  for (const g of guides) {
    const created = g.publishedAt ? `${q(g.publishedAt)}::timestamptz` : "now()";
    parts.push(`do $seed$
declare v_author uuid; v_id uuid;
begin
  v_author := coalesce((select author_id from public.guide_authors where guide_id = ${q(g.id)}), ${firstAuthor});
  if v_author is null then raise notice 'No author account yet: skipped guide ${g.id}'; return; end if;
  select id into v_id from public.content where kind = 'guide' and slug = ${q(g.id)};
  if v_id is null then
    insert into public.content (author_id, kind, title, description, price, status, tags, slug, created_at)
    values (v_author, 'guide', ${q(g.title)}, ${q(g.description)}, ${num(g.price)}, 'published', ${arr(g.tags)}, ${q(g.id)}, ${created})
    returning id into v_id;
  end if;
  insert into public.content_guide_meta (content_id, source, guide_type, category, tag, pages, read_minutes, relevant_if, outcomes, outline, pdf_meta)
  values (v_id, ${q(g.source ?? (g.guideContent && g.guideContent.length ? "sensoria_structured" : "uploaded_pdf"))}, ${q(g.guideType)}, ${q(g.category)}, ${q(g.tag)}, ${Number(g.pages) || 0}, ${Number(g.readMinutes) || 0}, ${arr(g.relevantIf)}, ${arr(g.outcomes)}, ${json(g.outline)}, ${json(g.pdf)})
  on conflict (content_id) do update set source = excluded.source, guide_type = excluded.guide_type, category = excluded.category, tag = excluded.tag,
    pages = excluded.pages, read_minutes = excluded.read_minutes, relevant_if = excluded.relevant_if, outcomes = excluded.outcomes, outline = excluded.outline, pdf_meta = excluded.pdf_meta;
  insert into public.content_guide_body (content_id, file_url, blocks)
  values (v_id, ${q(g.fileUrl || null)}, ${json(g.guideContent)})
  on conflict (content_id) do update set file_url = excluded.file_url, blocks = excluded.blocks;
end
$seed$;
`);
  }
  return parts.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const built = await buildSeed();
  if (process.argv.includes("--check")) {
    const cur = (() => { try { return readFileSync(out, "utf8"); } catch { return ""; } })();
    if (cur !== built) { console.error("materials-seed.sql is out of date: run `npm run build:materials-seed`"); process.exit(1); }
  } else {
    writeFileSync(out, built);
    console.log(`wrote ${out} (${built.length} chars)`);
  }
}
