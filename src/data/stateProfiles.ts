// The State Profile content contract (RFC-002).
//
// - insight       — short, headline-level read of what's happening
//                    (previously `description`)
// - explanation    — previously `whatHappens`
// - validation     — previously `normalization`
// - recoveryFocus  — a single direction answering "what should I focus on
//                     first?" (previously a `recommendations: string[]`
//                     list — concrete program/meditation/practice
//                     recommendations belong to the Recommendation layer,
//                     not the State Profile)
// - recoveryFocusShort — the same answer as `recoveryFocus`, distilled to
//                     2-4 words. Not a separate idea and not independently
//                     authored — it exists only so the Result page's
//                     Analysis card can show "Основний фокус" as a short
//                     label instead of either a full sentence or a fake
//                     score, and doubles as the first milestone title on
//                     the journey path (see ResultPage.tsx). Keep it a
//                     genuine compression of `recoveryFocus`, not a new
//                     angle on the profile.
// - validationMilestone — the journey path's second milestone title (2-5
//                     words). A genuine compression of `validation` (the
//                     "this is understandable, not a personal failing"
//                     idea), not a new angle on the profile. Draft copy,
//                     not yet reviewed.
// - stepMilestone  — the journey path's third milestone title (2-5
//                     words). A genuine compression of `recoveryFocus`/
//                     `hope`'s forward-looking idea — a small next step,
//                     distinct wording from `recoveryFocusShort` so the
//                     three milestones don't repeat each other. Draft
//                     copy, not yet reviewed.
// - hope           — communicates that the state is understandable,
//                     temporary, and can improve with consistent
//                     practice. Not motivational copy — it's meant to
//                     read as a conclusion that follows from insight →
//                     explanation → validation, not a standalone
//                     encouraging line.
// - focusSupportLine — one short sentence (single line, not a paragraph)
//                     explaining briefly why `recoveryFocusShort` is the
//                     right place to start. Currently unrendered — the
//                     Result page's journey-path section reads
//                     `recoveryFocus`/`hope` directly instead (see
//                     ResultPage.tsx's Support Point section comment).
